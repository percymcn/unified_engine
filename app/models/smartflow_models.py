class SmartFlowPattern(Base):
    """
    Recognized flow patterns with historical performance.
    ML learns which patterns precede winning trades.
    """
    __tablename__ = "smartflow_patterns"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(100), nullable=False)
    description = Column(Text, nullable=True)

    # Pattern definition
    pattern_features = Column(JSON, nullable=False)
    pattern_type = Column(String(50), nullable=False)  # sweep, block, split, multi_leg

    # Historical performance
    total_occurrences = Column(Integer, default=0)
    win_count = Column(Integer, default=0)
    loss_count = Column(Integer, default=0)
    win_rate = Column(Float, default=0.0)
    avg_pnl = Column(Float, default=0.0)
    avg_pnl_winner = Column(Float, default=0.0)
    avg_pnl_loser = Column(Float, default=0.0)
    expectancy = Column(Float, default=0.0)
    profit_factor = Column(Float, default=0.0)

    # Confidence
    confidence_score = Column(Float, default=50.0)
    sample_size_weight = Column(Float, default=0.0)

    # Best conditions
    best_hour = Column(Integer, nullable=True)
    best_day = Column(Integer, nullable=True)
    best_regime = Column(String(20), nullable=True)

    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)


class SmartFlowSignalOutcome(Base):
    """
    Track P&L outcomes of signals for ML learning.
    This is the feedback loop that enables self-improvement.
    """
    __tablename__ = "smartflow_signal_outcomes"

    id = Column(Integer, primary_key=True, index=True)
    signal_log_id = Column(Integer, ForeignKey("smartflow_signal_logs.id"), nullable=False)

    # Trade outcome
    trade_executed = Column(Boolean, default=False, nullable=False)
    entry_price = Column(Float, nullable=True)
    exit_price = Column(Float, nullable=True)
    pnl = Column(Float, nullable=True)
    pnl_percent = Column(Float, nullable=True)
    is_winner = Column(Boolean, nullable=True)

    # Timing
    time_to_target = Column(Integer, nullable=True)
    time_in_trade = Column(Integer, nullable=True)
    max_favorable_excursion = Column(Float, nullable=True)
    max_adverse_excursion = Column(Float, nullable=True)

    # Market context at signal
    market_regime = Column(String(20), nullable=True)
    vix_level = Column(Float, nullable=True)
    spy_price = Column(Float, nullable=True)
    hour_of_day = Column(Integer, nullable=True)
    day_of_week = Column(Integer, nullable=True)

    # Flow context
    flow_pattern = Column(JSON, nullable=True)
    pattern_id = Column(Integer, ForeignKey("smartflow_patterns.id"), nullable=True)

    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)

    # Relationships
    signal_log = relationship("SmartFlowSignalLog")
    pattern = relationship("SmartFlowPattern")


class SmartFlowModelState(Base):
    """
    ML model parameters and adaptive thresholds per ticker.
    Stores learned optimizations.
    """
    __tablename__ = "smartflow_model_state"

    id = Column(Integer, primary_key=True, index=True)
    ticker = Column(String(10), nullable=False, unique=True)

    # Adaptive thresholds (learned from outcomes)
    optimal_buy_threshold = Column(Float, default=4.0)
    optimal_sell_threshold = Column(Float, default=-4.0)
    optimal_close_threshold = Column(Float, default=1.0)

    # Confidence calibration
    fss_accuracy_by_range = Column(JSON, nullable=True)
    confidence_multiplier = Column(Float, default=1.0)

    # Time optimization
    hourly_win_rates = Column(JSON, nullable=True)
    best_trading_hours = Column(JSON, nullable=True)
    avoid_hours = Column(JSON, nullable=True)

    # Day optimization
    daily_win_rates = Column(JSON, nullable=True)
    best_trading_days = Column(JSON, nullable=True)

    # Recent performance
    recent_win_rate = Column(Float, default=0.5)
    recent_expectancy = Column(Float, default=0.0)
    recent_signals_count = Column(Integer, default=0)

    # Model versioning
    model_version = Column(Integer, default=1)
    last_trained_at = Column(DateTime, nullable=True)
    training_samples = Column(Integer, default=0)

    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)


