"""
SmartFlow Database Models
=========================

Models for SmartFlow Indicator configuration and signal logs.
"""

from sqlalchemy import Column, Integer, String, Float, Boolean, DateTime, Text, ForeignKey, JSON
from sqlalchemy.orm import relationship
from datetime import datetime

from app.db.database import Base


class SmartFlowConfig(Base):
    """
    SmartFlow configuration per user

    Stores user's preferences for SmartFlow Indicator:
    - Enable/disable toggle
    - Webhook URLs to post signals to
    - Score thresholds
    - Update intervals
    """
    __tablename__ = "smartflow_config"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False, unique=True)

    # Enable/disable
    enabled = Column(Boolean, default=False, nullable=False)

    # Webhook configuration
    webhook_urls = Column(JSON, nullable=False, default=list)  # List of webhook URLs to post signals to

    # Score thresholds
    buy_threshold = Column(Float, default=4.0, nullable=False)  # Score > this = buy signal
    sell_threshold = Column(Float, default=-4.0, nullable=False)  # Score < this = sell signal
    close_threshold = Column(Float, default=1.0, nullable=False)  # |Score| < this after extreme = close

    # Configuration
    score_window_minutes = Column(Integer, default=5, nullable=False)  # Flow window for scoring
    update_interval_seconds = Column(Integer, default=45, nullable=False)  # How often to compute scores

    # Enhanced toggles
    enable_vix_inverse = Column(Boolean, default=False, nullable=False)  # VIX/UVXY inverse sentiment
    enable_golden_sweeps = Column(Boolean, default=False, nullable=False)  # Golden sweep bonuses
    enable_leveraged_etfs = Column(Boolean, default=False, nullable=False)  # Use leveraged ETFs (SPXL/SPXU, etc.)
    vix_golden_threshold = Column(Float, default=100000.0, nullable=False)  # VIX golden sweep threshold
    min_premium = Column(Float, default=50000.0, nullable=False)  # Minimum flow premium to count

    # Confirmation filter toggles
    enable_price_confirmation = Column(Boolean, default=False, nullable=False)  # EMA filter
    enable_rsi_filter = Column(Boolean, default=False, nullable=False)  # RSI overbought/oversold filter
    enable_volume_filter = Column(Boolean, default=False, nullable=False)  # Volume spike requirement
    enable_time_filter = Column(Boolean, default=False, nullable=False)  # Time-of-day guard
    enable_fib_confluence = Column(Boolean, default=False, nullable=False)  # Fibonacci retracement bonus
    min_confidence_score = Column(Float, default=70.0, nullable=False)  # Minimum confidence % to execute

    # Confirmation filter parameters
    rsi_overbought = Column(Float, default=70.0, nullable=False)
    rsi_oversold = Column(Float, default=30.0, nullable=False)
    volume_spike_multiplier = Column(Float, default=1.5, nullable=False)
    time_filter_start_hour = Column(Integer, default=9, nullable=False)  # Market open hour (9am EST)
    time_filter_start_minute = Column(Integer, default=30, nullable=False)  # Market open minute (9:30am EST)
    time_filter_end_hour = Column(Integer, default=15, nullable=False)  # 3pm EST
    time_filter_end_minute = Column(Integer, default=0, nullable=False)  # End minute

    # AI Strategy Suite integration
    enable_ai_enhancement = Column(Boolean, default=False, nullable=False)  # Enable AI analysis
    ai_analysis_types = Column(JSON, default=['technical', 'patterns'])  # Analysis types to run
    block_on_ai_disagree = Column(Boolean, default=True, nullable=False)  # Block signals when AI disagrees
    check_market_trend = Column(Boolean, default=True, nullable=False)  # Check actual price trend
    # AI-Only Mode (24/7 trading)
    enable_ai_only_mode = Column(Boolean, default=False, nullable=False)  # Trade without flow data
    ai_only_scan_interval = Column(Integer, default=300, nullable=False)  # Seconds between scans
    ai_only_confidence_threshold = Column(Float, default=70.0, nullable=False)  # Min confidence to trade
    ai_only_instruments = Column(JSON, default=['MES', 'NQ', 'RTY', 'USDJPY', 'BTCUSD'])  # Instruments to trade

    # Metadata
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)

    # Relationships
    # user = relationship("User")  # One-way relationship, no back_populates needed
    signal_logs = relationship("SmartFlowSignalLog", back_populates="config", cascade="all, delete-orphan")


class SmartFlowSignalLog(Base):
    """
    Log of SmartFlow signals generated

    Stores history of all signals generated by SmartFlow for audit/analysis.
    """
    __tablename__ = "smartflow_signal_logs"

    id = Column(Integer, primary_key=True, index=True)
    config_id = Column(Integer, ForeignKey("smartflow_config.id"), nullable=False)

    # Signal details
    ticker = Column(String(10), nullable=False, index=True)  # MES, NQ, GC
    action = Column(String(10), nullable=False)  # buy, sell, close
    score = Column(Float, nullable=False)  # Sentiment score at signal time
    price = Column(Float, nullable=True)  # Price at signal time (if available)

    # Flow context
    bullish_flows = Column(Integer, default=0)  # Count of bullish flows in window
    bearish_flows = Column(Integer, default=0)  # Count of bearish flows in window
    total_premium = Column(Float, default=0.0)  # Total premium in window

    # AI-Only mode fields
    confidence = Column(Float, nullable=True)  # AI confidence % (for AI-Only signals)
    reason = Column(Text, nullable=True)  # AI reasoning or flow details

    # Webhook posting
    webhooks_posted = Column(JSON, nullable=False, default=list)  # List of webhook URLs posted to
    post_successful = Column(Boolean, default=False)  # All webhooks succeeded
    post_errors = Column(Text, nullable=True)  # Any errors encountered

    # Metadata
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)

    # Relationships
    config = relationship("SmartFlowConfig", back_populates="signal_logs")


